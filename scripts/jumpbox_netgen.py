#!/usr/bin/env python3
"""Render the jumpbox's router configuration from the lab VLAN address plan.

The jumpbox is the gateway, DHCP server and DNS forwarder for every lab VLAN.
Each VLAN tag maps to one /24:

    10.<tag - offset>.<third>.1/24

A *band* is a contiguous run of tags sharing an offset and third octet:

    name:first-last:offset:third

The defaults reproduce the reference deployment and cover every tag the
portal's VLAN allocator can hand out (app/vlan_allocator.py; the group pools
come from GROUP_ENTRY_VLAN_* / GROUP_INTERNAL_VLAN_* in app/config.py, and
allocator bounds are inclusive):

    entry           100-200 -> 10.100.0.1 .. 10.200.0.1   per-student entry networks
    group-entry     300-399 -> 10.100.2.1 .. 10.199.2.1   group entry networks
    group-internal  400-500 -> 10.100.4.1 .. 10.200.4.1   group internal networks

Per-student internal VLANs (200-300) are not served by the jumpbox. If the
portal's pools change, set JUMPBOX_VLAN_BANDS to match them.

Used by jumpbox_configure.sh; standard library only, so it runs on a stock
Ubuntu jumpbox.
"""

import argparse
import difflib
import ipaddress
import re
import sys

DEFAULT_BANDS = (
    "entry:100-200:0:0 "
    "group-entry:300-399:200:2 "
    "group-internal:400-500:300:4"
)
DEFAULT_DHCP_START = 50
DEFAULT_DHCP_END = 254
DEFAULT_LEASE = "12h"
HEADER = ("Generated by scripts/jumpbox_configure.sh. Change scripts/site.env "
          "and re-run it; edits here are overwritten.")

_IFNAME = re.compile(r"^[A-Za-z0-9_.-]{1,15}$")
_MAC = re.compile(r"^([0-9A-Fa-f]{2}:){5}[0-9A-Fa-f]{2}$")
_HOSTNAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9-]{0,62}$")
_LEASE = re.compile(r"^([0-9]+[smhdw]?|infinite)$")


class Band:
    __slots__ = ("name", "first", "last", "offset", "third")

    def __init__(self, name, first, last, offset, third):
        self.name, self.first, self.last = name, first, last
        self.offset, self.third = offset, third

    def tags(self):
        return range(self.first, self.last + 1)


def parse_bands(spec):
    """Parse a band spec, rejecting overlaps and tags that yield no address."""
    bands = []
    for item in spec.split():
        match = re.fullmatch(r"([a-z][a-z0-9-]*):(\d+)-(\d+):(\d+):(\d+)", item)
        if not match:
            raise ValueError(f"bad VLAN band {item!r}; expected name:first-last:offset:third")
        name = match.group(1)
        first, last, offset, third = (int(match.group(i)) for i in range(2, 6))
        if not 2 <= first <= last <= 4094:
            raise ValueError(f"band {name}: VLAN tags must satisfy 2 <= first <= last <= 4094")
        if not (0 <= first - offset and last - offset <= 255 and 0 <= third <= 255):
            raise ValueError(f"band {name}: 10.<tag-{offset}>.{third}.0/24 is not an address for every tag")
        bands.append(Band(name, first, last, offset, third))
    if not bands:
        raise ValueError("no VLAN bands configured")
    seen_tags, seen_nets = {}, {}
    for band in bands:
        for tag in band.tags():
            net = (tag - band.offset, band.third)
            if tag in seen_tags:
                raise ValueError(f"VLAN {tag} is in bands {seen_tags[tag]} and {band.name}")
            if net in seen_nets:
                raise ValueError(f"VLAN {tag} and VLAN {seen_nets[net]} map to the same subnet")
            seen_tags[tag], seen_nets[net] = band.name, tag
    return bands


def vlan_tags(bands):
    return [tag for band in bands for tag in band.tags()]


def _band_for(tag, bands):
    for band in bands:
        if band.first <= tag <= band.last:
            return band
    raise ValueError(f"VLAN {tag} is not in any routed band")


def _prefix(tag, bands):
    band = _band_for(tag, bands)
    return f"10.{tag - band.offset}.{band.third}"


def gateway(tag, bands):
    return f"{_prefix(tag, bands)}.1/24"


def dhcp_pool(tag, bands, start=DEFAULT_DHCP_START, end=DEFAULT_DHCP_END):
    if not 2 <= start <= end <= 254:
        raise ValueError("DHCP pool must satisfy 2 <= start <= end <= 254 (.1 is the gateway)")
    prefix = _prefix(tag, bands)
    return f"{prefix}.{start}", f"{prefix}.{end}"


def _ifname(name):
    if not _IFNAME.match(name or ""):
        raise ValueError(f"invalid interface name {name!r}")
    return name


def render_netplan(mgmt_if, trunk_if, bands):
    mgmt_if, trunk_if = _ifname(mgmt_if), _ifname(trunk_if)
    if mgmt_if == trunk_if:
        raise ValueError("management and trunk interfaces must differ")
    lines = [
        f"# {HEADER}",
        "network:",
        "  version: 2",
        "  ethernets:",
        f"    {mgmt_if}:",
        "      dhcp4: true",
        f"    {trunk_if}:",
        "      dhcp4: false",
        "  vlans:",
    ]
    for tag in vlan_tags(bands):
        lines += [
            f"    vlan{tag}:",
            f"      id: {tag}",
            f"      link: {trunk_if}",
            f"      addresses: [{gateway(tag, bands)}]",
        ]
    return "\n".join(lines) + "\n"


def _reservation(spec, bands):
    try:
        band_name, rest = spec.split("=", 1)
        mac, name, host = rest.split(",")
        host = int(host)
    except ValueError:
        raise ValueError(f"bad DHCP reservation {spec!r}; expected band=MAC,name,host") from None
    if band_name not in {b.name for b in bands}:
        raise ValueError(f"DHCP reservation {spec!r}: unknown band {band_name!r}")
    if not _MAC.match(mac) or not _HOSTNAME.match(name) or not 2 <= host <= 254:
        raise ValueError(f"DHCP reservation {spec!r}: need a MAC, a hostname and a host number 2-254")
    return band_name, mac, name, host


def render_dnsmasq(mgmt_if, bands, upstreams, reservations=(), start=DEFAULT_DHCP_START,
                   end=DEFAULT_DHCP_END, lease=DEFAULT_LEASE):
    mgmt_if = _ifname(mgmt_if)
    if not _LEASE.match(lease):
        raise ValueError(f"invalid lease time {lease!r}")
    if not upstreams:
        raise ValueError("at least one upstream DNS server is required")
    parsed = [_reservation(r, bands) for r in reservations]
    lines = [
        f"# {HEADER}",
        "# DHCP and DNS only on the lab VLAN interfaces: never on the management",
        "# LAN or the tailnet. bind-dynamic picks up VLAN interfaces as they appear",
        "# and leaves systemd-resolved's 127.0.0.53 alone.",
        "interface=vlan*",
        "bind-dynamic",
        f"no-dhcp-interface={mgmt_if}",
        "no-resolv",
    ]
    for server in upstreams:
        ipaddress.ip_address(server)
        lines.append(f"server={server}")
    for band in bands:
        lines.append(f"# {band.name}: VLAN {band.first}-{band.last}")
        held = [(mac, name, host) for b, mac, name, host in parsed if b == band.name]
        for tag in band.tags():
            first, last = dhcp_pool(tag, bands, start, end)
            lines.append(f"dhcp-range={first},{last},255.255.255.0,{lease}")
            prefix = _prefix(tag, bands)
            for mac, name, host in held:
                lines.append(f"dhcp-host={mac},{name},{prefix}.{host},infinite")
    return "\n".join(lines) + "\n"


def render_sysctl():
    return "\n".join([
        f"# {HEADER}",
        "# The jumpbox routes between the lab VLANs and the tailnet.",
        "net.ipv4.ip_forward = 1",
        "net.ipv6.conf.all.forwarding = 1",
        "# Loose reverse-path filtering: replies to tailnet clients arrive on a",
        "# VLAN interface but route back out tailscale0.",
        "net.ipv4.conf.all.rp_filter = 2",
        "net.ipv4.conf.default.rp_filter = 2",
    ]) + "\n"


def render_zeek_node(trunk_if):
    return "\n".join([
        f"# {HEADER}",
        "[zeek]",
        "type=standalone",
        "host=localhost",
        f"interface={_ifname(trunk_if)}",
    ]) + "\n"


def render_zeek_networks(routes):
    lines = [f"# {HEADER}"]
    for route in routes:
        lines.append(f"{ipaddress.ip_network(route)}\tLab VLAN networks")
    return "\n".join(lines) + "\n"


def unified_diff(path, current, generated):
    return "".join(difflib.unified_diff(
        current.splitlines(keepends=True), generated.splitlines(keepends=True),
        fromfile=f"{path} (current)", tofile=f"{path} (generated)"))


def _split(value, separators=r"[\s,]+"):
    return [v for v in re.split(separators, value or "") if v]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("what", choices=[
        "netplan", "dnsmasq", "sysctl", "zeek-node", "zeek-networks", "vlans", "diff"])
    parser.add_argument("--bands", default=DEFAULT_BANDS)
    parser.add_argument("--mgmt-if")
    parser.add_argument("--trunk-if")
    parser.add_argument("--upstream", default="")
    parser.add_argument("--reservations", default="")
    parser.add_argument("--dhcp-start", type=int, default=DEFAULT_DHCP_START)
    parser.add_argument("--dhcp-end", type=int, default=DEFAULT_DHCP_END)
    parser.add_argument("--lease", default=DEFAULT_LEASE)
    parser.add_argument("--routes", default="10.0.0.0/8")
    parser.add_argument("--label", help="diff: path shown in the header")
    parser.add_argument("files", nargs="*", help="diff: CURRENT GENERATED")
    args = parser.parse_args(argv)

    try:
        if args.what == "diff":
            current_path, generated_path = args.files
            try:
                with open(current_path) as fh:
                    current = fh.read()
            except FileNotFoundError:
                current = ""
            with open(generated_path) as fh:
                generated = fh.read()
            sys.stdout.write(unified_diff(args.label or current_path, current, generated))
            return 0
        if args.what == "sysctl":
            out = render_sysctl()
        elif args.what == "zeek-node":
            out = render_zeek_node(args.trunk_if)
        elif args.what == "zeek-networks":
            out = render_zeek_networks(_split(args.routes))
        else:
            bands = parse_bands(args.bands or DEFAULT_BANDS)
            if args.what == "vlans":
                out = "\n".join(f"vlan{t}" for t in vlan_tags(bands)) + "\n"
            elif args.what == "netplan":
                out = render_netplan(args.mgmt_if, args.trunk_if, bands)
            else:
                out = render_dnsmasq(
                    args.mgmt_if, bands, _split(args.upstream), _split(args.reservations, r"\s+"),
                    args.dhcp_start, args.dhcp_end, args.lease)
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
